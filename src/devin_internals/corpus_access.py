"""Access to the packaged fixture corpora (``devin_internals/corpus/``).

Both committed corpora ship inside the wheel as package data so downstream
repos stop vendoring byte-copies that drift:

- ``session-corpus`` — the SESSION-SURFACES §7 session-surface corpus
  (``manifest.json`` + ``evidence-manifest.json``), generated by
  ``devin_internals.session_corpus`` and consumed by the qa-pack audit.
- ``install-states`` — the SURFACE-HEALTH §7 installation-state corpus
  (``install-states-manifest.json``), generated by
  ``devin_internals.install_states`` and consumed by the doctor.

``corpus_root()`` exposes the tree read-only via ``importlib.resources``;
``materialize_corpus()`` copies a corpus to a real directory because
consumers need real files — sqlite stores must be openable paths and
fixture trees are passed around as ``Path`` roots. The committed copies
under ``fixtures/`` stay the source of truth; a test byte-compares the
packaged tree against them so the two can never silently diverge.
"""

from __future__ import annotations

import sys
from importlib.resources import files
from pathlib import Path

if sys.version_info >= (3, 11):
    from importlib.resources.abc import Traversable
else:  # 3.10: Traversable lives in importlib.abc
    from importlib.abc import Traversable

CORPORA = ("session-corpus", "install-states")

__all__ = ["CORPORA", "corpus_root", "materialize_corpus"]


def corpus_root(name: str | None = None) -> Traversable:
    """Return the packaged corpus root — ``corpus/`` itself, or the named
    corpus dir (one of :data:`CORPORA`) — as an ``importlib.resources``
    ``Traversable``. Read-only; use ``materialize_corpus`` when a real
    on-disk tree is needed."""
    root = files("devin_internals") / "corpus"
    if name is None:
        return root
    if name not in CORPORA:
        raise ValueError(f"unknown corpus {name!r}; expected one of {CORPORA}")
    return root / name


def materialize_corpus(dest: str | Path, name: str = "session-corpus") -> Path:
    """Copy the packaged ``name`` corpus into ``dest`` and return ``dest``.

    ``dest`` becomes the corpus root — after the call,
    ``dest / "manifest.json"`` etc. exist directly. ``dest`` must not
    already hold files (same owned-directory discipline as the corpus
    generators: no silent merge with unrelated content).
    """
    src = corpus_root(name)
    dest = Path(dest)
    if dest.exists() and any(dest.iterdir()):
        raise FileExistsError(
            f"{dest} is not empty — materialize into a fresh directory"
        )
    dest.mkdir(parents=True, exist_ok=True)
    _copy_tree(src, dest)
    return dest


def _copy_tree(src: Traversable, dst: Path) -> None:
    """Recursive copy over the Traversable API — works for plain
    filesystem installs and zip-imported resources alike."""
    for child in src.iterdir():
        target = dst / child.name
        if child.is_dir():
            target.mkdir()
            _copy_tree(child, target)
        else:
            target.write_bytes(child.read_bytes())
