def _file_listing(root: Path) -> dict[str, bytes]:
    return {
        str(p.relative_to(root)): p.read_bytes()
        for p in sorted(root.rglob("*"))
        if p.is_file()
    }


def test_corpus_is_deterministic(tmp_path):
    a, b = tmp_path / "a", tmp_path / "b"
    build_install_states(a)
    build_install_states(b)
    assert _file_listing(a) == _file_listing(b)


def test_manifest_shape(tmp_path):
    root = tmp_path / "corpus"
    manifest_path = build_install_states(root)
    m = json.loads(manifest_path.read_text())

    assert m["version"] == 1
    assert m["spec"] == "docs/SURFACE-HEALTH.md"
    assert set(m["unmodeled_states"]) == {"locked-or-unreadable"}

    order = {c: i for i, c in enumerate(CHECKS)}
    surfaces_seen: set[str] = set()
    for fixture in m["fixtures"]:
        assert fixture["surface"] in SURFACES
        surfaces_seen.add(fixture["surface"])
        assert (root / fixture["store_path"]).is_dir()
        checks = [f["check"] for f in fixture["expected_findings"]]
        # findings are emitted in ladder order, each rung at most once
        assert checks == sorted(checks, key=order.get)
        assert len(set(checks)) == len(checks)
        for f in fixture["expected_findings"]:
            assert set(f) <= {"check", "status", "code", "note"}
            assert f["status"] in STATUSES
            if "code" in f:
                assert f["code"] in ALLOWED_FINDING_CODES
                assert f["status"] in {"WARN", "FAIL"}
            if "note" in f:
                assert f["note"] in ALLOWED_NOTES
                assert f["status"] == "PASS"
        # a FAIL stops the ladder: it is always the last emitted finding
        statuses = [f["status"] for f in fixture["expected_findings"]]
        if "FAIL" in statuses:
            assert statuses[-1] == "FAIL"
    assert surfaces_seen == set(SURFACES)

    # states cover the required matrix (§7)
    states = {(f["surface"], f["state"]) for f in m["fixtures"]}
    for surface in SURFACES:
        for state in ("healthy", "absent", "empty-store", "corrupt-store",
                      "schema-unknown"):
            assert (surface, state) in states
    assert ("devin-cli", "schema-old") in states
    assert ("devin-cli", "missing-store") in states
    assert ("copilot-cli", "missing-store") in states

    # nothing content-shaped reaches the manifest — vocabulary only
    blob = manifest_path.read_text()
    for forbidden in ("xyzzy", "/fixture/workspace", "chat_message"):
        assert forbidden not in blob


def test_install_states_manifest_matches_artifacts(tmp_path):
    """Re-derive expected findings from the generated bytes — the
    hand-written manifest must match what the stores actually present
    (the same drift posture as test_evidence_manifest_matches_artifacts)."""
    root = tmp_path / "corpus"
    build_install_states(root)
    m = json.loads((root / "install-states-manifest.json").read_text())

    assert len(m["fixtures"]) >= 25  # every planned (surface, state) pair
    for fixture in m["fixtures"]:
        fixture_root = root / fixture["store_path"]
        derived = _CHECKERS[fixture["surface"]](fixture_root)
        assert derived == fixture["expected_findings"], (
            f"{fixture['surface']}/{fixture['state']}: manifest expects "
            f"{fixture['expected_findings']} but bytes derive {derived}"
        )


