def _logical_dump(db_path: Path) -> str:
    con = sqlite3.connect(db_path)
    try:
        return "\n".join(con.iterdump())
    finally:
        con.close()


def test_committed_corpus_matches_generator(tmp_path):
    """The vendored fixtures/install-states/ must be identical to a fresh
    build — committing the artifacts without this check lets them silently
    drift from the generator (same posture as the session-corpus test)."""
    committed = Path(__file__).resolve().parents[1] / "fixtures" / "install-states"
    build_install_states(tmp_path / "corpus")
    fresh = _file_listing(tmp_path / "corpus")
    vendored = _file_listing(committed)
    assert fresh.keys() == vendored.keys()
    for name in fresh:
        if name.endswith((".sqlite", ".db")) and fresh[name][:16] == SQLITE_MAGIC:
            assert _logical_dump(committed / name) == _logical_dump(
                tmp_path / "corpus" / name
            ), name
        else:
            # Same LF rule as the session corpus: only the vendored side
            # may legitimately carry CRLF from a core.autocrlf checkout.
            assert fresh[name] == vendored[name].replace(b"\r\n", b"\n"), name
