"""Install-state corpus tests (docs/SURFACE-HEALTH.md §7).

Covers three things: the builders produce the documented store layouts,
``build_install_states`` is byte-deterministic, and
``install-states-manifest.json`` validates against its declared shape —
including a reference checker that re-derives the expected findings from
the generated bytes, so the manifest can never silently drift from what a
conformant doctor must report.
"""

from __future__ import annotations

import json
import sqlite3
from pathlib import Path

from devin_internals.fixtures import (
    LATEST_KNOWN_SCHEMA,
    MIN_SUPPORTED_SCHEMA,
)
from devin_internals.install_states import (
    ALLOWED_FINDING_CODES,
    ALLOWED_NOTES,
    CHECKS,
    STATUSES,
    SURFACES,
    build_install_states,
    main,
)

SQLITE_MAGIC = b"SQLite format 3\x00"

# SESSION-SURFACES §6.5 — keys that make a chatSessions doc recognizable.
VSCODE_RECOGNIZABLE_KEYS = {
    "requests",
    "customTitle",
    "title",
    "creationDate",
    "lastMessageDate",
    "version",
    "requesterUsername",
    "responderUsername",
    "sessionId",
    "initialLocation",
    "isImported",
    "agent",
}

COPILOT_ENVELOPE_KEYS = {"id", "parentId", "timestamp", "type", "data"}


# ---------------------------------------------------------------------------
# Reference checker — a minimal, honest re-implementation of the
# SURFACE-HEALTH §3 ladder over a fixture dir. Kept deliberately small: it
# exists so the manifest's expected findings are re-derived from bytes, not
# trusted.
# ---------------------------------------------------------------------------


def _f(check: str, status: str, code: str | None = None,
       note: str | None = None) -> dict:
    f: dict = {"check": check, "status": status}
    if code is not None:
        f["code"] = code
    if note is not None:
        f["note"] = note
    return f


def _has_sqlite_magic(path: Path) -> bool:
    return path.read_bytes()[:16] == SQLITE_MAGIC


def _sqlite_tables(path: Path) -> set[str]:
    con = sqlite3.connect(f"file:{path.as_posix()}?mode=ro", uri=True)
    try:
        return {
            r[0]
            for r in con.execute(
                "SELECT name FROM sqlite_master WHERE type = 'table'"
            )
        }
    finally:
        con.close()


def _count_rows(path: Path, table: str) -> int | None:
    """COUNT(*) when the table exists, else None (not cheaply countable)."""
    if table not in _sqlite_tables(path):
        return None
    con = sqlite3.connect(f"file:{path.as_posix()}?mode=ro", uri=True)
    try:
        return con.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]
    finally:
        con.close()


def _first_jsonl_record(path: Path) -> object | None:
    """The raw parsed first non-empty line, or None when it does not parse
    as JSON at all (a non-dict JSON value is a schema matter, §3.3 — not
    corruption)."""
    for line in path.read_text().splitlines():
        if not line.strip():
            continue
        try:
            return json.loads(line)
        except json.JSONDecodeError:
            return None
    return None


def _sqlite_file_findings(path: Path) -> str | None:
    """Shared readable logic for a single sqlite artifact: returns the FAIL
    code when corrupt, ``"empty"`` when zero bytes, else None."""
    if path.stat().st_size == 0:
        return "empty"
    if not _has_sqlite_magic(path):
        return "store-corrupt"
    return None


def _devin_cli(root: Path) -> list[dict]:
    root_dir = root / "devin"
    db = root_dir / "cli" / "sessions.db"
    if not root_dir.is_dir():
        return [_f("present", "PASS", note="not-installed")]
    if not db.exists():
        return [_f("present", "WARN", code="store-missing")]
    findings = [_f("present", "PASS")]
    verdict = _sqlite_file_findings(db)
    if verdict == "store-corrupt":
        return findings + [_f("readable", "FAIL", code="store-corrupt")]
    if verdict == "empty":
        return findings + [_f("sane", "WARN", code="empty-store")]
    findings.append(_f("readable", "PASS"))
    tables = _sqlite_tables(db)
    version = None
    if "refinery_schema_history" in tables:
        con = sqlite3.connect(f"file:{db.as_posix()}?mode=ro", uri=True)
        try:
            version = con.execute(
                "SELECT MAX(version) FROM refinery_schema_history"
            ).fetchone()[0]
        finally:
            con.close()
    if version is None or int(version) > LATEST_KNOWN_SCHEMA:
        findings.append(_f("schema", "WARN", code="schema-unknown"))
    elif int(version) < MIN_SUPPORTED_SCHEMA:
        findings.append(_f("schema", "WARN", code="schema-old"))
    else:
        findings.append(_f("schema", "PASS"))
    n = _count_rows(db, "sessions")
    if n is not None and n == 0:
        findings.append(_f("sane", "WARN", code="store-empty"))
    else:
        findings.append(_f("sane", "PASS"))
    return findings


def _devin_chat(root: Path) -> list[dict]:
    roots = [root / "Devin", root / "devin"]
    if not any(r.is_dir() for r in roots):
        return [_f("present", "PASS", note="not-installed")]
    acp_dirs = [r / "User" / "acp-messages" for r in roots]
    acp_dirs = [d for d in acp_dirs if d.is_dir()]
    if not acp_dirs:
        return [_f("present", "WARN", code="store-missing")]
    findings = [_f("present", "PASS")]
    dbs = sorted(
        p for d in acp_dirs for p in d.iterdir() if p.suffix == ".db"
    )
    if not dbs:
        return findings + [_f("sane", "WARN", code="store-empty")]
    verdicts = [_sqlite_file_findings(db) for db in dbs]
    if "store-corrupt" in verdicts:
        return findings + [_f("readable", "FAIL", code="store-corrupt")]
    non_empty = [db for db, v in zip(dbs, verdicts) if v is None]
    if not non_empty:
        return findings + [_f("sane", "WARN", code="empty-store")]
    findings.append(_f("readable", "PASS"))
    if not all({"meta", "messages"} <= _sqlite_tables(db) for db in non_empty):
        findings.append(_f("schema", "WARN", code="schema-unknown"))
    else:
        findings.append(_f("schema", "PASS"))
    counts = [
        c
        for c in (_count_rows(db, "messages") for db in non_empty)
        if c is not None
    ]
    if counts and all(c == 0 for c in counts):
        findings.append(_f("sane", "WARN", code="store-empty"))
    else:
        findings.append(_f("sane", "PASS"))
    return findings


def _copilot_cli(root: Path) -> list[dict]:
    root_dir = root / ".copilot"
    if not root_dir.is_dir():
        return [_f("present", "PASS", note="not-installed")]
    containers = [
        root_dir / name
        for name in ("session-state", "history-session-state")
        if (root_dir / name).is_dir()
    ]
    if not containers:
        return [_f("present", "WARN", code="store-missing")]
    findings = [_f("present", "PASS")]
    jsonl_files = sorted(
        p
        for c in containers
        for p in c.rglob("*.jsonl")
        if p.is_file() and p.name != ".gitkeep"
    )
    if not jsonl_files:
        return findings + [_f("sane", "WARN", code="store-empty")]
    non_empty = [p for p in jsonl_files if p.stat().st_size > 0]
    if not non_empty:
        return findings + [_f("sane", "WARN", code="empty-store")]
    records = {p: _first_jsonl_record(p) for p in non_empty}
    if any(rec is None for rec in records.values()):
        return findings + [_f("readable", "FAIL", code="store-corrupt")]
    findings.append(_f("readable", "PASS"))
    if not all(
        isinstance(rec, dict) and COPILOT_ENVELOPE_KEYS <= set(rec)
        for rec in records.values()
    ):
        findings.append(_f("schema", "WARN", code="schema-unknown"))
    else:
        findings.append(_f("schema", "PASS"))
    findings.append(_f("sane", "PASS"))
    return findings


def _codex_cli(root: Path) -> list[dict]:
    root_dir = root / ".codex"
    if not root_dir.is_dir():
        return [_f("present", "PASS", note="not-installed")]
    state_dbs = sorted(root_dir.glob("state_*.sqlite"))
    rollout_dirs = [
        d
        for d in (root_dir / "sessions", root_dir / "archived_sessions")
        if d.is_dir()
    ]
    rollouts = sorted(
        p for d in rollout_dirs for p in d.glob("*.jsonl") if p.is_file()
    )
    if not state_dbs and not rollout_dirs:
        return [_f("present", "WARN", code="store-missing")]
    findings = [_f("present", "PASS")]
    if not state_dbs:
        # rollout-only store: readable/schema judge the JSONL leg
        if not rollouts:
            return findings + [_f("sane", "WARN", code="store-empty")]
        non_empty = [p for p in rollouts if p.stat().st_size > 0]
        if not non_empty:
            return findings + [_f("sane", "WARN", code="empty-store")]
        if any(_first_jsonl_record(p) is None for p in non_empty):
            return findings + [_f("readable", "FAIL", code="store-corrupt")]
        return findings + [_f("readable", "PASS"), _f("schema", "PASS"),
                           _f("sane", "PASS")]
    db = state_dbs[-1]  # largest N wins (§6.4)
    verdict = _sqlite_file_findings(db)
    if verdict == "store-corrupt":
        return findings + [_f("readable", "FAIL", code="store-corrupt")]
    if verdict == "empty":
        return findings + [_f("sane", "WARN", code="empty-store")]
    findings.append(_f("readable", "PASS"))
    suffix_numeric = db.stem.removeprefix("state_").isdigit()
    if not suffix_numeric or "threads" not in _sqlite_tables(db):
        findings.append(_f("schema", "WARN", code="schema-unknown"))
    else:
        findings.append(_f("schema", "PASS"))
    n = _count_rows(db, "threads")
    if n == 0 and not rollouts:
        findings.append(_f("sane", "WARN", code="store-empty"))
    else:
        findings.append(_f("sane", "PASS"))
    return findings


def _vscode_chat(root: Path) -> list[dict]:
    variants = [root / "Code", root / "Code - Insiders"]
    users = [v / "User" for v in variants if v.is_dir()]
    if not users:
        return [_f("present", "PASS", note="not-installed")]
    containers: list[Path] = []
    for user in users:
        storage = user / "workspaceStorage"
        if storage.is_dir():
            containers.extend(
                ws / "chatSessions"
                for ws in storage.iterdir()
                if (ws / "chatSessions").is_dir()
            )
        global_storage = user / "globalStorage"
        for name in ("emptyWindowChatSessions", "transferredChatSessions"):
            if (global_storage / name).is_dir():
                containers.append(global_storage / name)
    if not containers:
        return [_f("present", "WARN", code="store-missing")]
    findings = [_f("present", "PASS")]
    files = sorted(
        p
        for c in containers
        for p in c.iterdir()
        if p.is_file() and p.suffix in {".json", ".jsonl"}
    )
    if not files:
        return findings + [_f("sane", "WARN", code="store-empty")]
    non_empty = [p for p in files if p.stat().st_size > 0]
    if not non_empty:
        return findings + [_f("sane", "WARN", code="empty-store")]

    def parsed(p: Path) -> object | None:
        try:
            if p.suffix == ".jsonl":
                return _first_jsonl_record(p)
            return json.loads(p.read_text())
        except json.JSONDecodeError:
            return None

    docs = {p: parsed(p) for p in non_empty}
    if any(d is None for d in docs.values()):
        return findings + [_f("readable", "FAIL", code="store-corrupt")]
    findings.append(_f("readable", "PASS"))

    def recognizable(p: Path, doc: object) -> bool:
        if not isinstance(doc, dict):
            return False
        if p.suffix == ".jsonl":
            return doc.get("kind") in {0, 1, 2, 3}
        return bool(VSCODE_RECOGNIZABLE_KEYS & set(doc))

    if not all(recognizable(p, d) for p, d in docs.items()):
        findings.append(_f("schema", "WARN", code="schema-unknown"))
    else:
        findings.append(_f("schema", "PASS"))
    findings.append(_f("sane", "PASS"))
    return findings


_CHECKERS = {
    "devin-cli": _devin_cli,
    "devin-chat": _devin_chat,
    "copilot-cli": _copilot_cli,
    "codex-cli": _codex_cli,
    "vscode-chat": _vscode_chat,
}


